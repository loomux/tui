//go:build ignore

// gen_serverpin writes serverpin.go from the github.com/Loomux/server
// requirement in go.mod. Run it with `go generate ./...` after bumping the
// pin (`go get github.com/Loomux/server@v0.3.N`).
//
// The pin can't come from the binary's build info: only _test.go files
// import the server, so it isn't linked in.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"strings"
)

func main() {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Version}}", "github.com/Loomux/server")
	// Read go.mod, not a local go.work that points at a server checkout.
	cmd.Env = append(os.Environ(), "GOWORK=off")
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		log.Fatalf("go list -m github.com/Loomux/server: %v", err)
	}
	pin := strings.TrimSpace(string(out))
	if !strings.HasPrefix(pin, "v") {
		log.Fatalf("github.com/Loomux/server has no version in go.mod (got %q)", pin)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by gen_serverpin.go; DO NOT EDIT.

package version

// ServerPin is the github.com/Loomux/server release this client is built
// and tested against: its requirement in go.mod.
const ServerPin = %q
`, pin)
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("serverpin.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
